import test from 'node:test';
import assert from 'node:assert/strict';
import {promises as fs} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {defaultState,dateKey,addDays} from '../desktop/ui/model.mjs';
import {DesktopDriver,waitFor,delay,root} from './desktop-driver.mjs';
const event=(id,title,date,extra={})=>({id,title,startDate:date,endDate:date,startTime:'',endTime:'',category:'work',note:'',repeat:'none',repeatUntil:'',reminder:null,pinned:false,...extra});
test('서버 없는 데스크톱: 기존 UI, 저장, 완료, D-day, 트레이, 알림, 백업, 재실행',{timeout:90000},async()=>{
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'pet-calendar-desktop-'));
  const dataDir=path.join(dir,'data'),profile=path.join(dir,'profile');await fs.mkdir(dataDir);
  const initial=defaultState();initial.settings.hotkey.enabled=false;
  const today=dateKey();initial.events=[event('a','기존 일정 <한글>',today,{pinned:true,pinnedDate:today}),event('b','반복 회의',today,{repeat:'weekly'})];
  await fs.writeFile(path.join(dataDir,'calendar.json'),JSON.stringify(initial));
  let app=new DesktopDriver(dataDir,profile);
  try{
    await Promise.race([app.ready,new Promise((_,reject)=>setTimeout(()=>reject(new Error('Startup timeout '+app.diagnostic)),20000))]);
    assert.equal(await app.js('document.getElementById("loadingScreen").hidden'),true);
    assert.equal(await app.js('document.getElementById("deadlineTitle").textContent'),'기존 일정 <한글>');
    assert.equal(await app.js('document.getElementById("deadlineValue").textContent'),'D-day');
    assert.deepEqual(await app.js('window.qaErrors'),[]);
    assert.equal(await app.js('window.petCalendarDesktop'),true);
    const inspect=await app.command('inspect');assert.equal(inspect.applicationId,'PetCalendar.Desktop');assert.equal(inspect.visible,true);assert.equal(inspect.tray,true);
    await app.js('document.getElementById("taskTitle").value="숨겨도 남는 입력";true');
    await app.command('close-window');assert.equal((await app.command('inspect')).visible,false);
    await app.command('show');assert.equal(await app.js('document.getElementById("taskTitle").value'),'숨겨도 남는 입력');
    assert.equal(await app.js('Boolean(document.querySelector("#dayEvents [data-event-check=a]").closest(".day-event-card"))'),true);
    await app.js('document.querySelector("#dayEvents [data-event-check=a]").click();true');
    assert.equal(await app.js('document.getElementById("eventDialog").open'),false,'completion checkbox does not open editor');
    await waitFor(async()=>(await app.state()).events[0].completedDates.includes(today),'complete persisted');
    assert.equal(await app.js('document.getElementById("deadlineValue").textContent'),'D-day');
    let state=await app.state();const stale=structuredClone(state);state.tasks.push({id:'t',title:'마감이 있는 할 일',dueDate:addDays(today,1),done:false,createdAt:new Date().toISOString()});assert.equal((await app.save(state)).status,200);assert.equal((await app.save(stale)).status,409);
    state=await app.state();const bad=structuredClone(state);bad.events[0].endDate='bad';assert.equal((await app.save(bad)).status,400);
    assert.equal((await app.api('POST','/api/desktop/notification-test',undefined,{marker:''})).status,403);
    await app.command('hide');await app.api('POST','/api/desktop/notification-test');
    await waitFor(async()=>(await app.command('inspect')).popupVisible,'popup while hidden');
    let notification=await app.command('inspect');assert.equal(notification.visible,false);assert.equal(notification.pending.length,1);assert.equal(notification.soundBatches,1);
    await delay(16000);assert.equal((await app.command('inspect')).popupVisible,true);
    await app.close();app=new DesktopDriver(dataDir,profile);await app.ready;
    await waitFor(async()=>(await app.command('inspect')).popupVisible,'unread popup restored');
    notification=await app.command('inspect');assert.equal(notification.pending.length,1);assert.equal(notification.soundBatches,0);
    await app.command('alarm-ack');assert.equal((await app.command('inspect')).popupVisible,false);
    state=await app.state();state.settings.notificationSound=false;assert.equal((await app.save(state)).status,200);
    await app.api('POST','/api/desktop/notification-test');assert.equal((await app.command('inspect')).soundBatches,0);await app.command('alarm-ack');
    const backups=await fs.readdir(path.join(dataDir,'backups'));assert.ok(backups.length>=3);
    assert.equal((await app.state()).tasks[0].title,'마감이 있는 할 일');
    await app.command('capture',{path:path.join(root,'artifacts','desktop-native.png')});
    assert.deepEqual(await app.js('window.qaErrors'),[]);
    console.log(JSON.stringify({startupMs:app.startupMs,desktop:'native/no-server',popup:'sticky, restored, sound toggle verified'}));
  }finally{await app.close();await delay(500);await fs.rm(dir,{recursive:true,force:true}).catch(()=>{});}
});
