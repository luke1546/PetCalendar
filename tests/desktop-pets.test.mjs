import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {DesktopDriver,delay,waitFor,root} from './desktop-driver.mjs';
import {defaultState,dateKey} from '../desktop/ui/model.mjs';

test('설정에서 동물 사용: 기본 꺼짐, 메모리 해제, 7종, 캘린더 데이터·재시작 보존',{timeout:90000},async()=>{
 const temp=await fs.mkdtemp(path.join(os.tmpdir(),'calendar-pets-'));
 const data=path.join(temp,'data'),profile=path.join(temp,'profile');await fs.mkdir(data);
 const initial=defaultState();initial.settings.hotkey.enabled=false;
 initial.tasks=[{id:'pet-test',title:'동물 설정과 독립적인 할 일',dueDate:dateKey(),done:false,createdAt:new Date().toISOString()}];
 const file=path.join(data,'calendar.json'),original=JSON.stringify(initial);await fs.writeFile(file,original);
 let app=new DesktopDriver(data,profile);
 const inspect=async()=>(await app.command('pets-inspect')).pets;
 const click=selector=>app.js(`document.querySelector(${JSON.stringify(selector)}).click();true`);
 try {
  await app.ready;
  let state=await inspect();assert.equal(state.enabled,false);assert.equal(state.count,0);assert.equal(state.packLoaded,false);assert.equal(state.decodedAtlases,0);assert.equal(state.loopCount,0);
  assert.equal((await app.api('POST','/api/pets',{action:'enable'},{marker:''})).status,403);
  assert.equal((await app.api('POST','/api/pets',{action:'spawn',species:'cat'})).status,409);
  await click('#settingsButton');assert.equal(await app.js('document.querySelector("#petSettings").hidden'),false);
  assert.equal(await app.js('document.querySelector("#petsEnabled").checked'),false);
  await click('#petsEnabled');await waitFor(async()=>(await inspect()).count===1,'cat enabled');
  state=await inspect();assert.equal(state.pets[0].species,'cat');assert.equal(state.packLoaded,true);assert.equal(state.decodedAtlases,1);assert.equal(state.loopCount,1);
  assert.equal((await app.api('POST','/api/pets',{action:'spawn',species:'unknown'})).status,400);
  for(const kind of ['dog','redPanda','capybara','squirrel','alpaca','elephant'])assert.equal((await app.api('POST','/api/pets',{action:'spawn',species:kind})).status,200);
  state=await inspect();assert.equal(state.count,7);assert.equal(new Set(state.pets.map(p=>p.species)).size,7);assert.equal(state.decodedAtlases,7);
  assert.equal(state.pets.find(p=>p.species==='dog').palette,'하양');assert.equal(state.pets.find(p=>p.species==='alpaca').palette,'하양');assert.equal(state.pets.find(p=>p.species==='capybara').palette,'갈색');
  assert.ok(['기본 회색','밝은 회색'].includes(state.pets.find(p=>p.species==='elephant').palette));
  const cat=state.pets.find(p=>p.species==='cat'),dog=state.pets.find(p=>p.species==='dog');
  assert.equal(cat.name,'','older preferences default to unnamed');
  const name='호두 🐾 & <친구>';
  assert.equal((await app.api('POST','/api/pets',{action:'rename',window:cat.window,name})).status,200);
  assert.equal((await app.api('POST','/api/pets',{action:'rename',window:dog.window,name:'구름'})).status,200);
  for(const invalid of ['가'.repeat(25),'줄\n바꿈',null,true])assert.equal((await app.api('POST','/api/pets',{action:'rename',window:cat.window,name:invalid})).status,400);
  assert.equal((await app.api('POST','/api/pets',{action:'rename',window:cat.window,name:'변경 금지'},{marker:''})).status,403);
  assert.equal((await app.api('POST','/api/pets',{action:'rename',window:0,name:'없는 펫'})).status,404);
  assert.equal((await inspect()).pets.find(p=>p.species==='cat').name,name);
  assert.equal(await fs.readFile(file,'utf8'),original,'calendar bytes are not rewritten by pets');
  await app.js('document.getElementById("petSettings").open=true;document.getElementById("petSettings").scrollIntoView({block:"start"});true');await app.command('capture',{path:path.join(root,'artifacts','pets-settings.png')});
  await app.command('hide');assert.equal((await inspect()).count,7);await delay(300);await app.command('show');
  await app.close();app=new DesktopDriver(data,profile);await app.ready;
  state=await inspect();assert.equal(state.enabled,true);assert.equal(state.count,7,'opted-in pets return on restart');
  assert.equal(state.pets.find(p=>p.species==='cat').name,name,'name persists after restart');
  assert.equal(state.pets.find(p=>p.species==='dog').name,'구름','different pets keep separate names');
  assert.equal((await app.api('POST','/api/pets',{action:'rename',window:state.pets.find(p=>p.species==='cat').window,name:'  '})).status,200);
  assert.equal((await inspect()).pets.find(p=>p.species==='cat').name,'','empty name restores default display');
  await app.api('POST','/api/pets',{action:'disable'});state=await inspect();
  assert.equal(state.count,0);assert.equal(state.packLoaded,false);assert.equal(state.decodedAtlases,0);assert.equal(state.cacheBytes,0);assert.equal(state.loopCount,0);
  await app.close();app=new DesktopDriver(data,profile);await app.ready;
  state=await inspect();assert.equal(state.enabled,false);assert.equal(state.packLoaded,false);assert.equal(state.decodedAtlases,0);
  await app.api('POST','/api/pets',{action:'enable'});assert.equal((await inspect()).count,7,'enable restores chosen companions');
  await app.api('POST','/api/pets',{action:'disable'});
  assert.equal(await fs.readFile(file,'utf8'),original);
  assert.deepEqual(await app.js('window.qaErrors'),[]);
  assert.equal(await fs.stat(path.join(data,'pets.json')).then(()=>true),true);
  assert.equal(await fs.stat(path.join(data,'meowser-atlas.png')).then(()=>true,()=>false),false,'images are not extracted to disk');
 }finally {await app.close();await delay(300);await fs.rm(temp,{recursive:true,force:true}).catch(()=>{});}
});
