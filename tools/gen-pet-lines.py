"""Turn docs/pet-affinity-lines.md into desktop/PetLinesData.cs.

The markdown is the source of truth for affinity dialogue; run this after editing it:
    python tools/gen-pet-lines.py
"""
import io, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, 'docs', 'pet-affinity-lines.md')
TARGET = os.path.join(ROOT, 'desktop', 'PetLinesData.cs')

SPECIES = {'고양이': 'cat', '포메라니안': 'dog', '레서판다': 'redPanda', '카피바라': 'capybara',
           '다람쥐': 'squirrel', '알파카': 'alpaca', '코끼리': 'elephant'}
TIERS = {'존댓말': 0, '반말': 1, '애정': 2}
SITUATIONS = {'아침 인사': 'morning', '하나 완료': 'done1', '전부 완료': 'doneAll', '쓰다듬기': 'pet',
              '털실 공': 'toy', '오랜만': 'longtime', '일기 마무리': 'diaryEnd', '간식': 'snack'}


def parse(text):
    lines = {}      # "cat|0|morning" -> [..]
    levelup = {}    # "cat|2" -> line
    unlock = {}     # "cat|2" -> [..]
    species = tier = situation = section = level = None
    for raw in text.splitlines():
        m = re.match(r'## \S+ (\S+):', raw)
        if m:
            species = SPECIES[m.group(1)]; section = tier = situation = level = None; continue
        if species is None:
            continue
        m = re.match(r'### (\S+)', raw)
        if m:
            word = m.group(1)
            if word in TIERS:
                section, tier = 'tier', TIERS[word]
            elif word == '단계가':
                section = 'levelup'
            elif word == '새로':
                section = 'unlock'
            elif word == '배부를':
                section = 'full'
            continue
        if section == 'tier':
            m = re.match(r'- \*\*(.+?)\*\*$', raw)
            if m:
                situation = SITUATIONS[m.group(1)]; continue
            m = re.match(r'\s{2}- (.+)$', raw)
            if m:
                lines.setdefault('%s|%d|%s' % (species, tier, situation), []).append(m.group(1).strip())
        elif section == 'levelup':
            m = re.match(r'- \*\*(\d)단계:\*\* (.+)$', raw)
            if m:
                levelup['%s|%s' % (species, m.group(1))] = m.group(2).strip()
        elif section == 'full':
            m = re.match(r'- (.+)$', raw)
            if m:
                levelup['%s|full' % species] = m.group(1).strip()
        elif section == 'unlock':
            m = re.match(r'- \*\*(\d)단계\*\*$', raw)
            if m:
                level = m.group(1); continue
            m = re.match(r'\s{2}- (.+)$', raw)
            if m:
                unlock.setdefault('%s|%s' % (species, level), []).append(m.group(1).strip())
    return lines, levelup, unlock


def check(lines, levelup, unlock):
    for s in SPECIES.values():
        for t in range(3):
            for k in SITUATIONS.values():
                assert len(lines.get('%s|%d|%s' % (s, t, k), [])) >= 1, (s, t, k)
        for l in '2345':
            assert ('%s|%s' % (s, l)) in levelup, (s, l)
            assert len(unlock.get('%s|%s' % (s, l), [])) >= 1, (s, l)


def cs(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    lines, levelup, unlock = parse(io.open(SOURCE, encoding='utf-8').read())
    check(lines, levelup, unlock)
    out = ['// Generated by tools/gen-pet-lines.py from docs/pet-affinity-lines.md. Do not edit by hand.',
           'using System.Collections.Generic;', 'namespace PetCalendarDesktop {', '    internal static partial class PetLines {',
           '        static readonly Dictionary<string,string[]> lines=new Dictionary<string,string[]>{']
    for key in sorted(lines):
        out.append('            {%s,new[]{%s}},' % (cs(key), ','.join(cs(v) for v in lines[key])))
    out.append('        };')
    out.append('        static readonly Dictionary<string,string> levelUps=new Dictionary<string,string>{')
    for key in sorted(levelup):
        out.append('            {%s,%s},' % (cs(key), cs(levelup[key])))
    out.append('        };')
    out.append('        static readonly Dictionary<string,string[]> unlocks=new Dictionary<string,string[]>{')
    for key in sorted(unlock):
        out.append('            {%s,new[]{%s}},' % (cs(key), ','.join(cs(v) for v in unlock[key])))
    out += ['        };', '    }', '}', '']
    io.open(TARGET, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out))
    total = sum(len(v) for v in lines.values()) + len(levelup) + sum(len(v) for v in unlock.values())
    sys.stdout.write('wrote %s (%d lines)\n' % (os.path.relpath(TARGET, ROOT), total))


if __name__ == '__main__':
    main()
